"""Orders, ticks and fills.

The shape follows the execution model rather than the other way round: a day
places many orders, one per tick, and none of them is ever modified. So an
`Order` is a small immutable-ish thing with a price and a slice, a `Tick` is
the record of a five-minute moment whether or not it placed anything, and a
`Fill` is what the exchange actually did.

`Tick` rows exist for every tick, including the ones that placed nothing.
A day whose record has gaps cannot answer "why did nothing happen at 11:05?",
and that question is asked precisely when something has gone wrong (M21a).
"""

import uuid
from decimal import Decimal

from django.db import models

from orders.state import OrderState


class OrderSide(models.TextChoices):
    BUY = "BUY", "Buy"
    SELL = "SELL", "Sell"


class OrderMode(models.TextChoices):
    PAPER = "paper", "Paper"
    LIVE = "live", "Live"


class OrderType(models.TextChoices):
    LIMIT = "LIMIT", "Limit"
    MARKET = "MARKET", "Market"


#: The daily accumulation buy. Rebalance batches get their own stream, so that
#: a sell batch running alongside the ladder cannot collide with it on the
#: idempotency key (M24).
DAILY_BUY_STREAM = "daily_buy"


class NoPlaceReason(models.TextChoices):
    """Why a tick placed nothing. Never blank on a tick that placed nothing."""

    FULLY_COMMITTED = "fully_committed", "This name's quantity is already committed"
    OUTSIDE_SESSION = "outside_session", "Outside the market's hours"
    LOCKED_BOOK = "locked_book", "Locked or one-sided book"
    NO_DEPTH = "no_depth", "No usable depth"
    EXCLUDED = "excluded", "Excluded by the operator"
    LIVE_REFUSED = "live_refused", "Live placement refused by the engine"
    NO_SESSION = "no_session", "No Kite session"
    DAY_SKIPPED = "day_skipped", "The day is skipped"
    DAY_HALTED = "day_halted", "The day is halted after repeated rejections"
    PAUSED = "paused", "System paused"
    REJECTED = "rejected", "The broker rejected the order"
    FAILED = "failed", "The placement failed"
    NOT_AUTHORIZED = "not_authorized", "The day is not yet authorized to trade"
    RATE_BREAKER = "rate_breaker", "The order rate breaker tripped"
    RESTING = "resting", "An order for this name is resting"
    ON_SCHEDULE = "on_schedule", "On schedule; nothing is due yet"
    WAITING_TURN = "waiting_turn", "Due, waiting for the rate limit"
    WITHHELD = "withheld", "Withheld: the price left the sanity band"


class Order(models.Model):
    """One order, placed once and never modified (M21).

    `tag` is generated by this system *before* the broker is called, and is
    what makes an ambiguous placement recoverable: if the call times out, the
    recovery is to fetch the order book and look for the tag -- never to place
    again and hope.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    tag = models.CharField(
        max_length=32,
        unique=True,
        help_text="Generated before the broker call; how an ambiguous placement is recovered.",
    )

    tradesheet = models.ForeignKey(
        "engine.TradeSheet", on_delete=models.PROTECT, related_name="orders"
    )
    instrument = models.ForeignKey(
        "portfolio.Instrument", on_delete=models.PROTECT, related_name="orders"
    )

    trading_date = models.DateField(db_index=True)
    stream = models.CharField(max_length=32, default=DAILY_BUY_STREAM, db_index=True)
    tick_no = models.PositiveSmallIntegerField()

    side = models.CharField(max_length=4, choices=OrderSide.choices, default=OrderSide.BUY)
    mode = models.CharField(max_length=8, choices=OrderMode.choices)
    order_type = models.CharField(max_length=8, choices=OrderType.choices)
    is_fallback = models.BooleanField(
        default=False, help_text="The 15:00 market order, which runs the same table."
    )

    quantity = models.PositiveIntegerField()
    filled_quantity = models.PositiveIntegerField(default=0)
    limit_price = models.DecimalField(max_digits=14, decimal_places=4, null=True, blank=True)

    state = models.CharField(max_length=20, choices=OrderState.choices, default=OrderState.PLACED)
    kite_order_id = models.CharField(max_length=64, blank=True, db_index=True)
    #: The exchange's order number, from the order book, a postback's read
    #: of it, or the trade book. Console's tradebook names orders by it
    #: rather than by Kite's id (NI1).
    #: A database default too, so a row written by code that predates the
    #: column (a migration's historical model) still inserts.
    exchange_order_id = models.CharField(
        max_length=64, blank=True, default="", db_default="", db_index=True
    )
    rejection_reason = models.CharField(max_length=255, blank=True)

    placed_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    trace_id = models.CharField(max_length=64, blank=True, db_index=True)

    class Meta:
        ordering = ["trading_date", "tick_no", "placed_at"]
        indexes = [
            models.Index(fields=["trading_date", "stream", "state"]),
            models.Index(fields=["state"]),
        ]
        constraints = [
            models.CheckConstraint(
                condition=models.Q(filled_quantity__lte=models.F("quantity")),
                name="filled_never_exceeds_ordered",
            )
        ]

    def __str__(self) -> str:
        return f"{self.tag}: {self.side} {self.quantity} {self.instrument_id} ({self.state})"

    @property
    def is_paper(self) -> bool:
        return self.mode == OrderMode.PAPER

    @property
    def unfilled_quantity(self) -> int:
        return self.quantity - self.filled_quantity

    @property
    def is_terminal(self) -> bool:
        from orders.state import is_terminal

        return is_terminal(self.state)

    @property
    def is_open(self) -> bool:
        """Still capable of filling, and therefore still committing cash."""
        return not self.is_terminal


class Tick(models.Model):
    """One moment of the ladder, whether or not it placed anything.

    The depth it read is stored with it. Months later, "why did it price at
    1650.55?" is answerable from this row alone, without anybody having to
    trust a reconstruction of what the book looked like.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    tradesheet = models.ForeignKey(
        "engine.TradeSheet", on_delete=models.PROTECT, related_name="ticks"
    )
    trading_date = models.DateField(db_index=True)
    stream = models.CharField(max_length=32, default=DAILY_BUY_STREAM)
    tick_no = models.PositiveSmallIntegerField()
    #: The name this rung was for. A day buys several names, and each gets its
    #: own row per tick; a row about the whole day -- skipped, no session --
    #: has none.
    instrument = models.ForeignKey(
        "portfolio.Instrument",
        on_delete=models.PROTECT,
        related_name="ticks",
        null=True,
        blank=True,
    )

    fired_at = models.DateTimeField(auto_now_add=True)
    trace_id = models.CharField(max_length=64, blank=True, db_index=True)

    best_bid = models.DecimalField(max_digits=14, decimal_places=4, null=True, blank=True)
    best_ask = models.DecimalField(max_digits=14, decimal_places=4, null=True, blank=True)
    #: The market's volume-weighted average price for the day so far, from the
    #: same quote -- not ours; what our fills averaged is read from the fills.
    vwap = models.DecimalField(max_digits=14, decimal_places=4, null=True, blank=True)
    depth_snapshot = models.JSONField(default=dict, blank=True)

    slice_qty = models.PositiveIntegerField(default=0)
    committed_before = models.PositiveIntegerField(default=0)
    order = models.OneToOneField(
        Order, on_delete=models.PROTECT, null=True, blank=True, related_name="tick"
    )

    no_place_reason = models.CharField(max_length=24, choices=NoPlaceReason.choices, blank=True)
    detail = models.CharField(max_length=255, blank=True)

    class Meta:
        ordering = ["trading_date", "tick_no"]
        constraints = [
            models.UniqueConstraint(
                fields=["trading_date", "stream", "tick_no", "instrument"],
                name="one_tick_row_per_name_per_moment",
                # A whole-day row has no instrument, and two of those for one
                # moment are still a duplicate.
                nulls_distinct=False,
            )
        ]

    def __str__(self) -> str:
        if self.order_id:
            return f"{self.trading_date} tick {self.tick_no}: placed {self.slice_qty}"
        return f"{self.trading_date} tick {self.tick_no}: {self.no_place_reason or 'nothing'}"

    @property
    def placed(self) -> bool:
        return self.order_id is not None


class Fill(models.Model):
    """What the exchange actually did, at the price it actually did it.

    `kite_trade_id` is unique, and that constraint is load-bearing: it is what
    stops a duplicate postback creating a second lot and consuming cash twice
    (D11). Carry is computed by summing these rows, never from a broker
    average (D6).
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    order = models.ForeignKey(Order, on_delete=models.PROTECT, related_name="fills")

    kite_trade_id = models.CharField(
        max_length=64,
        unique=True,
        help_text="The broker's trade id; for a paper fill, a generated one marked paper.",
    )

    quantity = models.PositiveIntegerField()
    price = models.DecimalField(max_digits=14, decimal_places=4)
    charges = models.DecimalField(
        max_digits=12,
        decimal_places=4,
        default=Decimal("0"),
        help_text="Estimated at fill from the rate card, finalised against the contract note.",
    )

    executed_at = models.DateTimeField()
    recorded_at = models.DateTimeField(auto_now_add=True)
    trace_id = models.CharField(max_length=64, blank=True, db_index=True)

    class Meta:
        ordering = ["executed_at"]
        indexes = [models.Index(fields=["order", "executed_at"])]

    def __str__(self) -> str:
        return f"{self.quantity} @ {self.price} on {self.order_id}"

    @property
    def gross(self) -> Decimal:
        return self.price * self.quantity

    @property
    def total_cost(self) -> Decimal:
        """Everything the shares cost, charges included (D6)."""
        return self.gross + self.charges


class TaskRun(models.Model):
    """One row per scheduled execution, claimed before the work is done.

    The unique constraint is the idempotency guarantee (M24): a tick that
    fires twice claims the same key twice and the second one loses. `stream`
    separates the daily buy from each rebalance batch, without which a sell
    batch running alongside the ladder would collide on every tick.

    `tick_no` is never null. Postgres does not collide NULLs, so a nullable
    column here would protect nothing at all.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    trading_date = models.DateField(db_index=True)
    task = models.CharField(max_length=64)
    stream = models.CharField(max_length=32, default=DAILY_BUY_STREAM)
    tick_no = models.PositiveSmallIntegerField(default=0)

    started_at = models.DateTimeField(auto_now_add=True)
    finished_at = models.DateTimeField(null=True, blank=True)
    succeeded = models.BooleanField(null=True, blank=True)
    detail = models.CharField(max_length=255, blank=True)
    trace_id = models.CharField(max_length=64, blank=True, db_index=True)

    class Meta:
        ordering = ["-started_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["trading_date", "task", "stream", "tick_no"],
                name="one_run_per_task_tick",
            )
        ]

    def __str__(self) -> str:
        return f"{self.trading_date} {self.task}/{self.stream} tick {self.tick_no}"


class QueuedPostback(models.Model):
    """A postback that arrived before the order it refers to.

    Kept rather than dropped: the usual reason is that the postback overtook
    the placement response that creates the local row, and it is the only
    notice this system gets that something happened at the exchange. One that
    is still unmatched half an hour later is not a race -- it is an order this
    system does not know about, and that is worth an alarm.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    order_id = models.CharField(max_length=64, db_index=True)
    received_at_key = models.CharField(
        max_length=64,
        help_text="The postback's own timestamp, so a duplicate does not queue twice.",
    )
    payload = models.JSONField()

    received_at = models.DateTimeField(auto_now_add=True, db_index=True)
    resolved_at = models.DateTimeField(null=True, blank=True, db_index=True)

    class Meta:
        ordering = ["received_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["order_id", "received_at_key"], name="one_queue_row_per_postback"
            )
        ]

    def __str__(self) -> str:
        state = "resolved" if self.resolved_at else "waiting"
        return f"postback for {self.order_id} ({state})"


class FeedHeartbeat(models.Model):
    """The tick feed's pulse, where a process other than the feed can read it.

    The feed runs in its own long-lived process and keeps its health in
    memory, which nothing else can see. The health endpoint and the dashboard
    need to know three things it cannot answer from there: is the process
    alive at all, is it connected, and has it heard from the market lately.
    One row, overwritten every few seconds -- a pulse, not a history; the
    history is in the logs.
    """

    SINGLETON = 1

    id = models.PositiveSmallIntegerField(primary_key=True, default=SINGLETON)
    beat_at = models.DateTimeField(help_text="When the feed process last wrote this row.")
    connected = models.BooleanField(default=False)
    subscribed = models.PositiveIntegerField(default=0)
    last_tick_at = models.DateTimeField(null=True, blank=True)
    reconnects = models.PositiveIntegerField(default=0)
    last_error = models.CharField(max_length=255, blank=True)

    def __str__(self) -> str:
        return f"feed {'connected' if self.connected else 'down'} at {self.beat_at:%H:%M:%S}"
